#!/usr/bin/env node
// Regenerates sw.js with the list of app files to cache for offline use and a content hash,
// so every change to the app produces a new cache version. Usage: node scripts/build-sw.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const walk = (d) => readdirSync(path.join(root, d)).flatMap((f) => { const p = path.join(d, f); return statSync(path.join(root, p)).isDirectory() ? walk(p) : [p]; });
const assets = ["index.html", "manifest.webmanifest",
  ...["css", "js", "data", "icons"].flatMap(walk),
  ...["docs/INSTALL.html", "docs/Case_Compass_User_Manual.pdf", "docs/Case_Compass_Quick_Start.pdf"].filter((f) => existsSync(path.join(root, f))),
  ...(existsSync(path.join(root, "samples")) ? walk("samples").filter((f) => /\.(pdf|docx|xlsx|csv|html)$/.test(f)) : []),
].map((p) => p.split(path.sep).join("/")).sort();
const hash = createHash("sha256");
for (const a of assets) hash.update(a).update(readFileSync(path.join(root, a)));
const version = `3.0.0-${hash.digest("hex").slice(0, 10)}`;
const sw = `// Case Compass service worker – generated by scripts/build-sw.mjs. Do not edit by hand.
// Caches only the application's own files for offline use. It never reads, stores, or sends
// your records (those live encrypted in IndexedDB) and it ignores all requests to other sites.
const VERSION = ${JSON.stringify(version)};
const CACHE = "case-compass-" + VERSION;
const ASSETS = ${JSON.stringify(["./", ...assets], null, 1)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS.map((a) => new Request(a, { cache: "reload" })))));
});
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith("case-compass-") && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});
self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never touch other sites
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (req.mode === "navigate") {
      const hit = await cache.match("./index.html") || await cache.match("./");
      try { const fresh = await fetch(req); return fresh.ok ? fresh : (hit || fresh); } catch { return hit || Response.error(); }
    }
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(req); } catch { return new Response("Offline and not cached", { status: 503, headers: { "Content-Type": "text/plain" } }); }
  })());
});
`;
writeFileSync(path.join(root, "sw.js"), sw);
console.log(`sw.js: ${assets.length} assets, version ${version}`);
