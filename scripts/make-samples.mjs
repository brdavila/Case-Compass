#!/usr/bin/env node
// Generates the clearly labeled, FICTIONAL sample export package in samples/ using the same
// report modules the app uses. Usage: node scripts/make-samples.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sampleRecords, sampleCtx } from "./sample-data.mjs";
import { buildReportModel, buildWorkbookModel, buildTimelineCSV, defaultOptions } from "../js/reports/model.js";
import { buildDocx } from "../js/reports/docx.js";
import { buildXlsx } from "../js/reports/xlsx.js";
import { buildPdf } from "../js/reports/pdf.js";
import { buildPrintHTML } from "../js/reports/html.js";
import { PROTOCOLS } from "../data/checklists-data.js";
import { GUIDES } from "../data/guides-data.js";

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../samples");
mkdirSync(out, { recursive: true });
const recs = sampleRecords();
const ctx = sampleCtx(recs, { protocols: PROTOCOLS, guides: GUIDES });

const monthly = { ...defaultOptions("monthly"), month: "2026-10", sample: true };
const m = buildReportModel(recs, monthly, ctx);
writeFileSync(path.join(out, "SAMPLE_Monthly_Report_October_2026.pdf"), buildPdf(m));
writeFileSync(path.join(out, "SAMPLE_Monthly_Report_October_2026.docx"), buildDocx(m));
writeFileSync(path.join(out, "SAMPLE_Monthly_Report_October_2026.html"), buildPrintHTML(m, { toolbar: false }));

const wb = buildWorkbookModel(recs, { ...defaultOptions("chronological"), sample: true, title: "Case workbook – October 2026" }, ctx);
writeFileSync(path.join(out, "SAMPLE_Case_Workbook_October_2026.xlsx"), buildXlsx(wb));

const att = buildReportModel(recs, { ...defaultOptions("attorney"), sample: true }, ctx);
writeFileSync(path.join(out, "SAMPLE_Attorney_Preparation_Packet.pdf"), buildPdf(att));
writeFileSync(path.join(out, "SAMPLE_Attorney_Preparation_Packet.docx"), buildDocx(att));

const ev = buildReportModel(recs, { ...defaultOptions("evidence"), sample: true }, ctx);
writeFileSync(path.join(out, "SAMPLE_Evidence_Index.pdf"), buildPdf(ev));

const pt = buildReportModel(recs, { ...defaultOptions("parenting"), sample: true, range: { start: "2026-10-01", end: "2026-10-31" } }, ctx);
writeFileSync(path.join(out, "SAMPLE_Parenting_Time_Record.pdf"), buildPdf(pt));

const chrono = buildReportModel(recs, { ...defaultOptions("chronological"), sample: true, title: "Chronological report" }, ctx);
writeFileSync(path.join(out, "SAMPLE_Chronological_Report.pdf"), buildPdf(chrono));

const cl = buildReportModel(recs, { ...defaultOptions("checklist"), sample: true }, ctx);
writeFileSync(path.join(out, "SAMPLE_Action_Checklists.pdf"), buildPdf(cl));

const blank = buildReportModel([], { ...defaultOptions("blank") }, ctx);
writeFileSync(path.join(out, "Blank_Record_Keeping_Forms.pdf"), buildPdf(blank));

writeFileSync(path.join(out, "SAMPLE_Timeline.csv"), buildTimelineCSV(recs, { ...defaultOptions("chronological"), sample: true }, ctx));
writeFileSync(path.join(out, "README.md"), `# Sample export package (FICTIONAL DATA)

Every name, date, and event in these files is invented to show what Case Compass exports look like.
They were generated by \`node scripts/make-samples.mjs\` using the same report code the app uses.
None of this data is ever loaded into the app; new installations start empty.

| File | Format | What it shows |
|---|---|---|
| SAMPLE_Monthly_Report_October_2026.pdf / .docx / .html | PDF, Word, print HTML | Monthly report |
| SAMPLE_Case_Workbook_October_2026.xlsx | Excel | 12-sheet workbook with frozen, filterable headers |
| SAMPLE_Attorney_Preparation_Packet.pdf / .docx | PDF, Word | Attorney packet (private notes and prior advice excluded) |
| SAMPLE_Evidence_Index.pdf | PDF | Evidence inventory with SHA-256 fingerprints |
| SAMPLE_Parenting_Time_Record.pdf | PDF | Requested vs. scheduled vs. completed comparison |
| SAMPLE_Chronological_Report.pdf | PDF | Court-oriented chronological report |
| SAMPLE_Action_Checklists.pdf | PDF | Protection & Security progress |
| SAMPLE_Timeline.csv | CSV | Timeline export |
| Blank_Record_Keeping_Forms.pdf | PDF | Blank printable logs (not official court forms) |
`);
console.log("samples written to", out);
